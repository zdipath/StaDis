class PatchEmbed(nn.Module):
    """2D Image to Patch Embedding as implemented in [1]_.

    Parameters
    ----------
    img_size:  int = 224
        Size of the input image (both height and width), by default 224.
    patch_size: int = 16
        Size of each patch, by default 16.
    in_chans: int = 3
        Number of input channels, by default 3.
    embed_dim: int = 768
        Dimension of the embedded patch representation, by default 768.

    Attributes
    ----------
    img_size: int
        Size of the input image (both height and width).
    patch_size: int
        Size of each patch.
    num_patches: int
        Total number of patches in the image.
    proj: nn.Conv2d
        Convolutional layer used for projection.


    References
    ----------
    .. [1] https://github.com/huggingface/pytorch-image-models/blob/main/timm/layers/patch_embed.py#L25
    """

    def __init__(
        self,
        img_size: int = 224,
        patch_size: int = 16,
        in_chans: int = 3,
        embed_dim: int = 768,
    ) -> None:
        super().__init__()
        num_patches = (img_size // patch_size) * (img_size // patch_size)
        self.img_size = img_size
        self.patch_size = patch_size
        self.num_patches = num_patches

        self.proj = nn.Conv2d(
            in_chans, embed_dim, kernel_size=patch_size, stride=patch_size
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """Forward pass of the PatchEmbed module.

        Parameters
        ----------
        x: torch.Tensor
            Input tensor of shape (``B``, ``C``, ``H``, ``W``) where ``B`` is the
            batch size, ``C`` is the number of channels, ``H`` is the input image
            height, and ``W`` is the input image width.

        Returns
        -------
        torch.Tensor
            Output tensor of shape (``B``, ``embed_dim``, ``num_patches``) where
            ``B`` is the batch size, ``embed_dim`` is the dimension of the embedded
            patch  representation, and ``num_patches`` is the total number of
            patches in the image.
        """
        #  B, C, H, W = x.shape
        return self.proj(x).flatten(2).transpose(1, 2)


def vit_base(patch_size: int = 16, **kwargs):
    """Create a Base Vision Transformer model (ViT-B).

    Parameters
    ----------
    patch_size : int = 16
        Size of the patches in the input image.
    **kwargs : keyword arguments
        Additional arguments to be passed to the VisionTransformer constructor.

    Returns
    -------
    model : VisionTransformer
        The Base Vision Transformer model.
    """
    model = VisionTransformer(
        patch_size=patch_size,
        embed_dim=768,
        depth=12,
        num_heads=12,
        mlp_ratio=4,
        qkv_bias=True,
        **kwargs
    )
    return model


class iBOTViT(Extractor):  # pylint: disable=abstract-method
    """Vision transform model trained with iBOT (See [1]_).

    Parameters
    ----------
    architecture: str = 'vit_base_pancan'
        Model architecture. Must only be "vit_base_pancan" as of now.
    encoder: str = 'teacher'
        Whether to load the weights from the student or teacher encoder.
    mean: Tuple[float, float, float] = IMAGENET_MEAN
        Mean values used for mean/std normalization of image channels.
    std: Tuple[float, float, float] = IMAGENET_STD:
        Std values used for mean/std normalization of image channels.

    References
    ----------
    .. [1] Jinghao Zhou, Chen Wei, Huiyu Wang, Wei Shen, Cihang Xie, Alan Yuille, and Tao Kong.
    Image BERT pre-training with online tokenizer. In International Conference on Learning
    Representations, 2022
    """

    def __init__(
        self,
        architecture="vit_base_pancan",
        encoder="teacher",
        mean: Tuple[float, float, float] = IMAGENET_MEAN,
        std: Tuple[float, float, float] = IMAGENET_STD,
        weights_path: Optional[str] = None,
        path='/home/zhangdi/mycode/paper1/models/ibot_vit.pth'
    ):
        super(iBOTViT, self).__init__()

        self.mean = mean
        self.std = std
        self.encoder = encoder

        # Load weights for iBOT[ViT-B]PanCancer.
        assert (
            architecture == "vit_base_pancan"
        ), "Weights are released for `vit_base_pancan` architecture only."
        self.backbone = vit_base(
            patch_size=16, num_classes=2, use_mean_pooling=False
        )
        self._weights_path = weights_path
        if self._weights_path is None:
            self._weights_path = path

        # Load state_dict.
        state_dict = torch.load(self._weights_path, map_location="cpu")
        state_dict = state_dict[self.encoder]
        state_dict = {
            k.replace("module.", ""): v for k, v in state_dict.items()
        }
        state_dict = {
            k.replace("backbone.", ""): v for k, v in state_dict.items()
        }
        # Set weights with state_dict.
        msg = self.backbone.load_state_dict(state_dict, strict=False)
        #logger.info(
        #    f"Pretrained weights found at {self._weights_path} and loaded with msg: {msg}"
        #)

    @property
    def transform(self):
        """Transform method to apply element wise.

        Returns
        -------
        transform: Callable[[Input], Transformed]
        """
        transform_ops = [
            transforms.ToTensor(),
            transforms.Normalize(
                mean=self.mean,
                std=self.std,
            ),
        ]
        return transforms.Compose(transform_ops)
    

    def __call__(self, images: torch.Tensor,n:int,output:bool) -> torch.Tensor:
        """
        Compute and return features.

        Parameters
        ----------
        images: torch.Tensor
            input of size (n_tiles, n_channels, dim_x, dim_y)

        Returns
        -------
        features : torch.Tensor
            tensor of size (n_tiles, features_dim)
        """
        # intermediate output
        # see https://github.com/facebookresearch/dino/blob/cb711401860da580817918b9167ed73e3eef3dcf/eval_linear.py#L208
        features = self.backbone.get_intermediate_layers(images, n)
        #features = torch.cat([x[:, 0] for x in features], dim=-1)
        if output==True:
            logit=features[n-1]
            return logit
        else:
            return features
    

